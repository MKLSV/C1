// Детектор кризисных сигналов. См. docs/architecture.md §5 (безопасность).
// Список намеренно консервативный; при срабатывании бот не продолжает
// профориентацию «как обычно», а мягко направляет к живой помощи.

const CRISIS_PATTERNS: RegExp[] = [
  /сув[ие]?сид/i, // суицид/суисид (опечатки)
  /суицид/i,
  /покончить с собой/i,
  /не хочу жить/i,
  /незачем жить/i,
  /руки на себя/i,
  /причинить себе вред/i,
  /смысла жить нет/i,
  /хочу умереть/i,
];

export function detectCrisis(text: string): boolean {
  return CRISIS_PATTERNS.some((re) => re.test(text));
}

